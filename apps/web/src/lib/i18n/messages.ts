// Fallback profundo: chave ausente → inglês → pt-BR (nunca vaza pt pra gringo).
function deepMerge<T>(base: T, over: unknown): T {
  if (Array.isArray(base) || Array.isArray(over)) {
    return (over === undefined ? base : over) as T;
  }
  if (typeof base !== "object" || base === null || over === null || typeof over !== "object") {
    return (over === undefined ? base : over) as T;
  }
  const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  for (const [k, v] of Object.entries(over as Record<string, unknown>)) {
    out[k] = deepMerge((base as Record<string, unknown>)[k], v);
  }
  return out as T;
}

export function getMessages(lang: Lang): Messages {
  const dict = messages[lang];
  if (lang === "pt") return pt;
  if (!dict || Object.keys(dict).length === 0) return messages.en;
  // Primeiro funde com en (base internacional), depois aplica o idioma.
  return deepMerge(deepMerge(pt, messages.en), dict);
}
